"""Run every benchmark and write ``evaluation/results/SUMMARY.md``.

    python -m evaluation.run_all

Every number in SUMMARY.md is read back from the CSV files written by the benchmark
scripts, so the summary cannot drift from the results.
"""
from __future__ import annotations

import pandas as pd

from evaluation import benchmark_embeddings, benchmark_roles, benchmark_speed, common


def _table(name: str, columns: list[str] | None = None, digits: int = 3) -> str:
    frame = pd.read_csv(common.RESULTS / f"{name}.csv")
    return common.to_markdown(frame[columns] if columns else frame, digits)


def write_summary() -> None:
    reps = pd.read_csv(common.RESULTS / "representations.csv")
    parts = [
        "# FootballIQ benchmark results",
        "",
        "Generated by `python -m evaluation.run_all`. Do not edit by hand.",
        "",
        "## 1. Data linkage",
        "", _table("data_linkage"),
        "",
        "## 2. Representations",
        "",
        "All rows are scored on the same outfield players (900+ minutes, present in both the "
        "original and the new table). Higher is better except `minutes_R2` (how well playing time "
        "can be predicted from the representation) and `same_club@10`. `role_MAP_own` uses only the "
        "project's own 58 role labels; `role_MAP_all` adds the unverified draft labels.",
        "",
        common.to_markdown(reps[["representation", "dim", "runs", "position_purity@10", "family_purity@10",
                                 "family_probe_F1", "minutes_R2", "same_club@10", "role_MAP_own",
                                 "role_MAP_all", "seed_stability@10"]]),
        "",
        "Standard deviation over seeds (stochastic models only):",
        "",
        common.to_markdown(reps.dropna(subset=["family_purity@10_sd"])[
            ["representation", "position_purity@10_sd", "family_purity@10_sd", "family_probe_F1_sd",
             "minutes_R2_sd", "role_MAP_own_sd", "role_MAP_all_sd"]]),
        "",
        "Paired bootstrap (10,000 resamples of players), family purity@10:",
        "", _table("representation_contrasts"),
        "",
        "### Embedding size",
        "", _table("dimension_sweep"),
        "",
        "## 3. Embedding a player when one view is missing",
        "",
        "Five-fold: players are held out of training, embedded from one view only, and compared "
        "with the embedding they get from both views.",
        "", _table("missing_view"),
        "",
        "## 4. Re-identifying a player across two club spells",
        "", _table("reidentification"),
        "",
        "## 5. Role classification",
        "",
        "### 5.1 The original rule engine: reported vs honest accuracy",
        "", _table("roles_original_engine"),
        "",
        "### 5.2 Held-out players (draft labels, unverified)",
        "", _table("roles_heldout"),
        "", _table("roles_mcnemar", digits=4),
        "",
        "### 5.3 Cross-validation over all labels",
        "", _table("roles_cross_validation"),
        "", _table("roles_gate_reachability"),
        "",
        "### 5.4 Accuracy against number of training labels",
        "", _table("roles_learning_curve"),
        "",
        "### 5.5 Per role (leave-one-out)",
        "", _table("roles_per_role"),
        "",
        "## 6. Query latency",
        "", _table("speed", digits=4),
        "",
    ]
    (common.RESULTS / "SUMMARY.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"\nwrote {common.RESULTS / 'SUMMARY.md'}")


def main() -> None:
    pd.set_option("display.width", 250)
    pd.set_option("display.max_columns", 30)
    benchmark_embeddings.main()
    benchmark_roles.main()
    benchmark_speed.main()
    write_summary()


if __name__ == "__main__":
    main()
